const assert=require('node:assert/strict');
const {certificateData,certificateSVG}=require('../js/certificate');
const {ADVENTURE_LEVELS}=require('../js/adventure');
const date=new Date(2026,9,23);
const full=certificateData('小宇',1,1,[3,3,1,3,3,3],date);
assert.equal(full.total,16);assert.equal(full.completed,6);assert.equal(full.title,'星辰小勇者');
assert.equal(full.route,'一年级上册');assert.equal(full.date,'2026年10月23日');
assert.equal(certificateData('',6,2,[3,3,3,3,3,3],date).title,'满星传奇探险家');
const partial=certificateData('   ',2,2,[3,0,0,0,0,0],date);
assert.equal(partial.title,'闪光小探险家');assert.equal(partial.completed,1);assert.equal(partial.total,3);
assert.equal(partial.name,'勇敢的小探险家');
assert.equal(certificateData('a\u0000b',1,1,[],date).name,'ab');
assert.equal(certificateData('星'.repeat(30),1,1,[],date).name.length,16);
assert.equal(Array.from(certificateData('🦊'.repeat(20),1,1,[],date).name).length,16);
const svg=certificateSVG(full,ADVENTURE_LEVELS);
assert.match(svg,/已通关 6 \/ 6 关/);assert.match(svg,/收集 16 \/ 18 颗星/);
assert.match(svg,/width="1600" height="1120"/);
assert.doesNotMatch(svg,/<image|<script|<foreignObject|(?:href|src)="https?:/);
const unsafe=certificateSVG(certificateData('<>&"\'',1,1,[1],date),ADVENTURE_LEVELS);
assert.match(unsafe,/&lt;&gt;&amp;&quot;&apos;/);
assert.equal((certificateSVG(partial,ADVENTURE_LEVELS).match(/待点亮/g)||[]).length,5);
console.log('证书测试通过：成果统计、部分通关/全通关/满星称号、姓名长度、转义及自绘图像。');
