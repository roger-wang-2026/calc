const assert=require('node:assert/strict');
const {T}=require('../js/generators');
const {adventureResult}=require('../js/adventure');
const {readMistakes,recordMistake,buildReview,completeReview}=require('../js/mistakes');
const level={count:5};
assert.deepEqual(adventureResult(level,5,5,5,5),{passed:true,stars:3});
assert.deepEqual(adventureResult(level,5,5,5,4),{passed:true,stars:2});
assert.deepEqual(adventureResult(level,5,5,5,3),{passed:true,stars:1});
assert.deepEqual(adventureResult(level,4,5,5,4),{passed:false,stars:0});
assert.equal(adventureResult(level,5,5,4,5).passed,false);
const unit=T[0],q=['1 + 1','2','='];
let entries=recordMistake([],q,'1-1',0,unit.n);
entries=recordMistake(entries,q,'1-1',0,unit.n);assert.equal(entries.length,1);
assert.deepEqual(readMistakes(JSON.stringify(entries),T),entries);
assert.deepEqual(readMistakes('bad',T),[]);
const malicious=JSON.parse(JSON.stringify(entries));malicious[0].question[0]='<img src=x onerror=alert(1)>';
assert.deepEqual(readMistakes(JSON.stringify(malicious),T),[]);
const other=recordMistake(entries,['3 + 1','4','='],'1-2',0,T.find(u=>u.g===1&&u.t===2).n);
let review=buildReview(other,T,'1-1');assert.equal(review.groups.length,1);assert.equal(review.questions.length,2);
assert.equal(review.questions[0][0],q[0]);assert.notEqual(review.questions[1][0],q[0]);
entries=completeReview(entries,review.groups,[true,false],10);assert.equal(entries[0].streak,0);
entries=completeReview(entries,review.groups,[true,true],20);assert.equal(entries[0].streak,1);
entries=completeReview(entries,review.groups,[true,true],30);assert.equal(entries[0].streak,2);
assert.equal(buildReview(entries,T,'1-1').questions.length,0);
entries=recordMistake(entries,q,'1-1',0,unit.n);assert.equal(entries[0].streak,0);
const many=Array.from({length:8},(_,i)=>({...entries[0],id:String(i),question:[`${i} + 1`,String(i+1),'=']}));
assert.equal(buildReview(many,T,'1-1').groups.length,5);
assert.equal(buildReview(entries,[{g:1,t:1,n:unit.n,f:()=>q}],'1-1').questions.length,1);
console.log('错题与评星测试通过：首次正确率边界、去重、年级隔离、原题/变式、两轮掌握、重错重置和存档校验。');
